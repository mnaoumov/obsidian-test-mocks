import {
  describe,
  expect,
  it
} from 'vitest';

import { findInlineBlockIds } from './markdown-inline-block-ids.ts';

describe('findInlineBlockIds', () => {
  // Each row is a one-paragraph note and the id Obsidian 1.14.4's own metadata worker gives that paragraph, which is the
  // last id its inline text holds.
  it.each([
    [String.raw`a\*^id`, 'id'],
    [String.raw`a\\^id`, 'id'],
    [String.raw`a\\\^id`, undefined],
    ['a`c`^id', 'id'],
    ['a*b*^id', 'id'],
    [String.raw`a\q^id`, undefined],
    [String.raw`\*^id`, 'id'],
    ['a*^id', undefined],
    ['a**b**^id', 'id'],
    ['a~~b~~^id', 'id'],
    ['a==b==^id', 'id'],
    ['a====b^id', undefined],
    ['a[[x]]^id', 'id'],
    ['a![[x]]^id', 'id'],
    ['a[[x[[y]]^id', 'id'],
    ['a#tag^id', undefined],
    ['a #tag^id', 'id'],
    ['a #12^id', undefined],
    ['a$x$^id', 'id'],
    ['a $ x$^id', undefined],
    ['a$x $^id', undefined],
    ['a $x$1^id', undefined],
    ['a $$x$$^id', 'id'],
    ['a $$x$$ \n^id', 'id'],
    ['a $$x$$  ^id', 'id'],
    [String.raw`a $\$x$^id`, 'id'],
    ['a$^id', undefined],
    ['a%%c%%^id', 'id'],
    ['%%a ^id%% b', 'id'],
    ['a[l](u)^id', 'id'],
    ['a[l](u(v))^id', 'id'],
    [String.raw`a[l](u\)v)^id`, 'id'],
    ['a[l](u^id', undefined],
    ['a[`]`](u)^id', undefined],
    ['![i ^x](u)^id', 'id'],
    ['a[ref]^id', 'id'],
    ['a[]^id', undefined],
    ['a[b][c]^id', 'id'],
    ['a[b][]^id', 'id'],
    ['a[b][c^id', undefined],
    ['a[[b]^id', 'id'],
    ['a[b [c]][d]^id', 'id'],
    ['![r]^id', 'id'],
    ['a<span>^id', 'id'],
    ['a<https://x.y>^id', 'id'],
    ['a<!-- c -->^id', 'id'],
    ['a<?p?>^id', 'id'],
    ['a<!X y>^id', 'id'],
    ['a<![CDATA[x]]>^id', 'id'],
    ['a<x@y.z>^id', 'id'],
    ['http://x.y^id', undefined],
    ['http://x.y.^id', undefined],
    ['http://^id', undefined],
    ['x www.a.b <b>^id', 'id'],
    ['x@y.z^id', 'id'],
    ['x@y.z.^id', 'id'],
    ['x@y.z-^id', 'id'],
    ['x@y^id', undefined],
    ['x@y.^id', undefined],
    ['@y.z^id', undefined],
    ['a@@y.z^id', undefined],
    ['a.@y.z^id', 'id'],
    ['*a ^id*', 'id'],
    ['**a ^id**', 'id'],
    ['[a ^id](u)', 'id'],
    ['a ^id b', undefined],
    ['*a ^id* b', 'id'],
    ['a ^[x^id', undefined],
    ['a[^1]^id', 'id'],
    ['a[^1 2]^id', undefined],
    ['a_b_^id', 'id'],
    ['a_b_c^id', undefined],
    ['a__b__^id', 'id'],
    ['a__ __^id', undefined],
    ['a**b***^id', 'id'],
    ['a** **^id', undefined],
    ['a* b*^id', 'id'],
    ['a**b*^id', 'id'],
    [String.raw`a*b\*c*^id`, 'id'],
    [String.raw`a**b\**c**^id`, 'id'],
    ['a ~~b ^id~~', 'id'],
    ['a ~~ b~~^id', undefined],
    ['a~~b ~~^id', undefined],
    ['a~~~~^id', 'id'],
    ['a===b===^id', undefined],
    ['a`x``^id', undefined],
    ['a``x``^id', 'id'],
    ['a`x^id', undefined],
    ['a\\', undefined],
    ['a\n^id', 'id'],
    ['a ``^id', undefined],
    ['a&amp;^id', undefined],
    ['a<^id', undefined],
    ['x ^a ^b', 'b'],
    [String.raw`a\-^id`, 'id'],
    ['a!^id', undefined],
    ['a![x^id', undefined],
    ['a~^id', undefined],
    ['a=^id', undefined],
    ['a%^id', undefined],
    ['a %%^id', undefined],
    ['a_^id', undefined],
    ['*a_b_ ^id*', 'id'],
    ['_a_b ^id_', 'id'],
    ['_a ^id_b_', undefined],
    ['a*`*`*^id', undefined],
    ['a ^id*', undefined],
    ['a ^id ', undefined],
    ['https://x.y)^id', undefined],
    ['a#^id', undefined],
    [String.raw`a[b\]c]^id`, 'id'],
    ['a[b[c]]^id', undefined],
    [String.raw`a[b][c\]d]^id`, 'id'],
    ['x@y.z-', undefined],
    ['x@y.z_', undefined],
    ['x@y.z.', undefined],
    ['*x@y.z.*^id', 'id'],
    ['http:// ^id', 'id'],
    ['a http://.<b>^id', 'id'],
    ['a[[ [[x]] ]]^id', undefined]
  ])('should read the id of %j as Obsidian does', (text, expectedId) => {
    expect(findInlineBlockIds(text).at(-1)).toBe(expectedId);
  });

  it('should list every id in document order, an id ending an inline token first', () => {
    expect(findInlineBlockIds('*a ^x* ^y')).toEqual(['x', 'y']);
  });

  it('should read no id in an inline footnote', () => {
    expect(findInlineBlockIds('a ^[n ^x]')).toEqual([]);
  });

  it('should read an id after an inline footnote', () => {
    expect(findInlineBlockIds('a ^[n]^x')).toEqual(['x']);
  });
});
